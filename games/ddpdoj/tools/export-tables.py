#
# So the set is enumerated in three parts, all from the ROM:
STAGE1_SCRIPT = 0x230C6C          # 8-byte records, $FFFF terminator
TYPE_TAB_LO, TYPE_TAB_HI = 0x267824, 0x27E412
MOVE_AUX, MOVE_RES, MOVE_RES_END, MOVE_N = 0x23170C, 0x231852, 0x2325D0, 163
PROTO_COPY = 0x2637A2             # the loader whose two forms src/enemyproto.js
PROTO_LONG_SPEED = 0x16           # ...documents: 28 table bytes -> $20 record
PROTO_SHORT_SPEED = 0x0E          # ...16 table bytes -> $20 record
# The RAMP CEILINGS, by ROM site.  These three handlers are the only stage-1
# code that steps `($1A,A6)` arithmetically, and each does it between 0 and a
# constant it compares against:
#   $26A69C subq.b #$1  / $26A420 addq.b #$1 until `$26A40C cmpi.b #$1C`  ($08)
#   $26A958 subq.b #$1  / $26A99E addq.b #$2 until `$26A98A cmpi.b #$20`  ($09)
#   $26AE1C subq.b #$1  / $26AEEA addq.b #$1 until `$26AED6 cmpi.b #$1C`  ($0B)
# so every integer from 0 up to the larger of (that type's prototype speed, its
# ceiling) is reachable, and the closure below is `range(0, max + 1)`.
RAMP_CEILINGS = {0x1C, 0x20}


def stage1_types(d: bytes) -> set[int]:
    """The types stage 1's script names, plus the three an ENEMY spawns."""
    out = {0x1C, 0x1E, 0x23}
    a = STAGE1_SCRIPT
    while u16(d, a) != 0xFFFF:
        out.add(u16(d, a + 4) >> 8)
        a += 8
    return out


def _type_entry(t: int) -> int:
    return (TYPE_TAB_LO if t < 0x80 else TYPE_TAB_HI - 0x80 * 8) + t * 8


def proto_speed_indices(d: bytes) -> set[int]:
    """Every sub-record prototype speed byte a stage-1 type spawns with.

    Finds each init body's `lea <proto>(pc),A0 / nop / jsr $2637A2` and decodes
    the prototype the way src/enemyproto.js does -- the word-0 SIGN picks the
    form, and both forms produce $20 record bytes from 28 or 16 table bytes.
    The sub-record count is the init STUB's own `move.w #$N,($4,A5)`, i.e. N+1
    records (the `dbra`)."""
    out: set[int] = set()
    for t in sorted(stage1_types(d)):
        init = u32(d, _type_entry(t))
        n = u16(d, init + 2)
        body = init + 8
        for off in range(0, 0x200, 2):
            a = body + off
            if (u16(d, a) == 0x41FA and u16(d, a + 4) == 0x4E71
                    and u16(d, a + 6) == 0x4EB9 and u32(d, a + 8) == PROTO_COPY):
                disp = struct.unpack_from(">h", d, a + 2)[0]
                cur = (a + 2 + disp) & 0xFFFFFF       # lea's PC is the operand word
                for _ in range(n + 1):
                    if u16(d, cur) & 0x8000:          # $2637AC, the LONG form
                        out.add(d[cur + PROTO_LONG_SPEED])
                        cur += 28
                    else:                             # $2637C2, the SHORT form
                        out.add(d[cur + PROTO_SHORT_SPEED])
                        cur += 16
    return out


def stream_speed_indices(d: bytes) -> set[int]:
    """Every SPEED operand in stage 1's 163 movement streams (`>= $C0` -> the
    next byte lands in `($1A,A6)`, `$26392C`).  The opcode lengths are the ones
    src/movement.js's twelve escapes consume."""
    aux = [u16(d, MOVE_AUX + 2 * i) for i in range(MOVE_N)]
    starts = [MOVE_RES + a for a in aux]
    lens = [(starts[i + 1] - starts[i]) if i + 1 < MOVE_N
            else MOVE_RES_END - starts[i] for i in range(MOVE_N)]
    esc_len = {0: 2, 1: 2, 2: 2, 3: 2, 4: 2, 5: 6, 6: 6, 7: 2, 8: 2, 9: 2,
               10: 1, 11: 1}
    out: set[int] = set()
    for st, ln in zip(starts, lens):
        j = 4                                          # the 4-byte X,Y header
        while j < ln:
            b = d[st + j]
            if b < 0x80:
                j += 2                                 # HEAD + its param
            elif b < 0xC0:
                j += esc_len[b & 0x0F]
            else:
                out.add(d[st + j + 1])                 # $26392C move.b (A0)+,($1a,A6)
                j += 2
    return out


def enemy_speed_indices(d: bytes) -> set[int]:
    """The closure: the prototypes, the streams, and the ramps between them."""
    protos = proto_speed_indices(d)
    streams = stream_speed_indices(d)
    top = max(protos | streams | RAMP_CEILINGS)
    return protos | streams | set(range(0, top + 1))


def u16(d: bytes, a: int) -> int:
    return struct.unpack_from(">H", d, a)[0]


def u32(d: bytes, a: int) -> int:
    return struct.unpack_from(">I", d, a)[0]


def i32(d: bytes, a: int) -> int:
    return struct.unpack_from(">i", d, a)[0]


def speed_levels(d: bytes) -> int:
    """How many speed levels the pointer table holds.

    NOT a guess: entry s must be exactly $200D20 + $208*s.  The count is where
    that stops holding.  WAVE 4 scanned to 64 and said so ("a SCAN CAP, not the
    end of the table"); WAVE 8 needs index 232 (the laser template's ($1a,A6))
    and re-ran the scan with the cap at 256.  MEASURED: the pattern holds for
    EXACTLY 256 entries -- $200920+4*256 and the two longs after it are zero,
    and the last table ends at $221520 -- so 256 is now the table's END and not
    a cap.  The verifier below asserts both halves of that.
    """
    base = u32(d, SPEED_PTRS)
    n = 0
    while n < SCAN_CAP and u32(d, SPEED_PTRS + 4 * n) == base + QUAD_STRIDE * n:
        n += 1
    return n


def spawn_templates(d: bytes) -> dict:
    """Walk $2554EA/$255502 exactly as $249BFC does and return the reachable
    38-byte templates keyed by ROM address.  This is a MEASUREMENT of what the
    spawn can read, not a guess at a table length: the walk is the ROM's own
    indexing arithmetic."""
    out = {}
    for tbl in SPAWN_PTR_TABLES:
        for form in range(SPAWN_FORMATION_ENTRIES):
            per_power = u32(d, tbl + 4 * form)
            for pw in range(SPAWN_POWERS):
                # $249C48 `move.w ($20,A6),D0 / add.w D0,D0 / movea.l (A1,D0.w),A1`
                # -- power word 0,2,4,6,8 becomes byte index 0,4,8,12,16.
                t = u32(d, per_power + 4 * pw)
                out[t] = list(d[t:t + TEMPLATE_LEN])
    return out


def speed_index_set(d: bytes) -> list[int]:
    """The speed levels the port can actually reach: the player's own 0..31 plus
    every ($1a,A6) byte in a reachable spawn template.  Exporting all 256 levels
    would put 133 KiB of quadrant tables into the published bundle for levels
    nothing reads; exporting a GUESSED subset would make the port read
    `undefined`.  So the set is derived, listed in the JSON, and the port throws
    by name on any index outside it."""
    s = set(range(PLAYER_SPEED_LEVELS))
    for t in spawn_templates(d).values():
        s.add(t[TEMPLATE_SPEED_OFF])
    # WAVE 12: and the OPTION PODS' own levels, from $24BBAA's templates.
    s.update(option_speed_indices(d))
    # W31: and the levels enemy handlers pass to $241D34 as an IN-CODE CONSTANT
    # rather than out of a template, which the walk above cannot see.  The
    # midboss's arm kinematics ($26B304) does `move.w #$70,D0` at BOTH
    # $26B3B2 and $26B3F8.  Listed with its call sites, exactly as W12 listed
    # the pods' 224 -- MEASURED: the port threw `speed index 112 was not
    # exported` on the first midboss frame before this line existed.
    s.update(HANDLER_SPEED_INDICES)
    # W36: and the ENEMIES' own levels -- the sub-record prototypes, the
    # movement streams' SPEED opcodes, and the arithmetic ramps between them.
    s.update(enemy_speed_indices(d))
    # W54: and THE DEATH EXPLOSION's, which is a new reader of $241D34 with a
    # new index domain.  `$288F18 move.b ($1a,A6),D0 / jsr $241D34` takes the
    # pool-B record's speed byte, and the death arms fill it two ways.
    s.update(effect_speed_indices(d))
    # W65: and THE LASER BOMB'S SPARK's, which is a new reader of $241812 with
    # a new index domain.  `$28A252` (pool E's fill tail for kind 0, reached
    # only from $289FF4) calls $241812 TWICE:
    #   $28A26C jsr $242E24 / $28A272 addq.b #$4,D0   -> $242E42[i] + 4, byte
    #   $28A284 move.w #$C0,D0                        -> the CONSTANT $C0
    # Both are ENUMERATED out of the image, not guessed and not measured: the
    # first is the whole 128-byte canned table plus the instruction's own 4,
    # the second is the instruction's own immediate.  W12 listed the pods' 224
    # the same way and W31 the midboss's 112.
    s.update(beam_spark_speed_indices(d))
    return sorted(s)


BEAM_SPARK_DRAW_TABLE = 0x242E42      # $242E24's canned bytes
BEAM_SPARK_ADD_AT = 0x28A272          # `addq.b #$4,D0`
BEAM_SPARK_CONST_AT = 0x28A284        # `move.w #$C0,D0`


def beam_spark_speed_indices(d: bytes) -> set[int]:
    """W65.  Every speed index `$28A252`'s two `$241812` calls can be handed."""
    # `addq.b #$4,D0` is $5800 -- the immediate is IN the opcode, so read it
    # rather than writing 4 here.
    op = u16(d, BEAM_SPARK_ADD_AT)
    if (op & 0xF1FF) != 0x5000:
        raise SystemExit(
            f"$28A272 is ${op:04X}, not an `addq.b #n,D0`; the LASER BOMB "
            f"spark's speed domain is derived from that immediate.")
    add = (op >> 9) & 7 or 8
    if u16(d, BEAM_SPARK_CONST_AT) != 0x303C:
        raise SystemExit(f"$28A284 is ${u16(d, BEAM_SPARK_CONST_AT):04X}, not "
                         f"`move.w #imm,D0`.")
    const = u16(d, BEAM_SPARK_CONST_AT + 2)
    out = {(b + add) & 0xFF for b in d[BEAM_SPARK_DRAW_TABLE:
                                       BEAM_SPARK_DRAW_TABLE + 128]}
    out.add(const)
    return out


# ---------------------------------------------------------------- WAVE 54
# `$289004`'s call sites, and what they leave in the effect record's ($1a,A0).
EFFECT_ALLOC = 0x289004
EFFECT_SCAN_LO, EFFECT_SCAN_HI, EFFECT_SCAN_AFTER = 0x230000, 0x2B0000, 96


def effect_speed_indices(d: bytes) -> set[int]:
    """W54.  Every speed index `$288F28 jsr $241D34` can be handed.

    ENUMERATED, not measured, and not guessed: walk every absolute-long
    `jsr/jmp $289004` in the image and read the instruction that fills the new
    record's `($1a,A0)` out of the bytes that follow it.  There are exactly two
    forms in the cartridge, and both are here:

      `317C iiii 001A`  move.w #imm,($1a,A0)   -- the HIGH byte is the speed
                                                  ($273E08's $0754 is speed 7)
      `1140 001A`       move.b D0,($1a,A0)     -- the damage-first family's
                                                  `$269D2E addq.b #8,D0` on the
                                                  DYING ENEMY's own ($1a,A6)

    The second form is why this function exists at all: [M] the port threw
    `speed index 37 was not exported` on the first family kill, 37 being an
    enemy speed of 29 plus that `addq.b #8`.  So the whole of
    `enemy_speed_indices` shifted up by 8 is in the domain, exactly as W12
    listed the pods' 224 and W31 the midboss's 112.
    """
    out: set[int] = set()
    shifted = False
    a = EFFECT_SCAN_LO
    while a < EFFECT_SCAN_HI - 6:
        if u16(d, a) in (0x4EB9, 0x4EF9) and u32(d, a + 2) == EFFECT_ALLOC:
            b = a + 6
            end = min(b + EFFECT_SCAN_AFTER, EFFECT_SCAN_HI - 6)
            while b < end:
                if u16(d, b) in (0x4EB9, 0x4EF9):       # the next call ends the arm
                    break
                if u16(d, b) == 0x317C and u16(d, b + 4) == 0x001A:
                    out.add(u16(d, b + 2) >> 8)
                    b += 6
                    continue
                if u16(d, b) == 0x1140 and u16(d, b + 2) == 0x001A:
                    shifted = True
                b += 2
        a += 2
    if not shifted:
        raise SystemExit(
            "W54: no `move.b D0,($1a,A0)` follows any of the $289004 call "
            "sites. $269D2E's `addq.b #8` on the dying enemy's own speed is "
            "the reason the effect pool can index $241D34 above every enemy "
            "level, and the scan can no longer see it.")
    out.update((s + 8) & 0xFF for s in enemy_speed_indices(d))
    return out


def check_pool_e_extents(d: bytes) -> None:
    """W53 (E5a).  ASSERT POOL E's DATA BLOCK AGAINST THE CARTRIDGE, every export.

    Three arithmetics close exactly on a landmark that is not a reading; if any
    of them stops closing, the block has moved and the export must STOP rather
    than ship 1,498 bytes of something else.  W47 §4.3's precedent, applied to a
    table whose extent is pinned by CODE rather than by a chain.
    """
    PTRS, N_PTRS = 0x28A786, 256
    end = PTRS + N_PTRS * 4                    # $28AB86
    if d[end:end + 6] != bytes((0x52, 0x39, 0x00, 0x80, 0x39, 0x17)):
        raise SystemExit(
            f"$28A786's pointer table: this file says {N_PTRS} entries ending at "
            f"${end:06X}, but ${end:06X} is not `addq.b #1,$803917` "
            f"({d[end:end + 6].hex()}). $289F68 indexes it with an UNMASKED "
            f"$803916, so a short table reads a template out of code.")
    tpls = sorted({u32(d, PTRS + 4 * i) for i in range(N_PTRS)})
    if len(tpls) != 15:
        raise SystemExit(f"$28A786 resolves to {len(tpls)} distinct pool-E "
                         f"templates; W53 measured 15.")
    LOW = 0x28A5AC
    if tpls[0] != LOW or tpls[-1] + 22 != PTRS:
        # The message prints BOTH sides from variables, so a mutation of the
        # EXPECTATION reads as clearly as a move of the cartridge.  (An earlier
        # version hardcoded $28A5AC in the text and printed the same range twice.)
        raise SystemExit(
            f"the pool-E templates run ${tpls[0]:06X}..${tpls[-1] + 22:06X}; "
            f"this file says ${LOW:06X}..${PTRS:06X} (the last template abutting "
            f"the pointer table EXACTLY).")
    lists = {u32(d, t + 0x10) for t in tpls}
    if lists != {0x28A5C2}:
        raise SystemExit(f"the 15 pool-E templates name descriptor lists "
                         f"{[hex(x) for x in sorted(lists)]}; W53 measured all "
                         f"fifteen naming $28A5C2 alone.")
    # The list's own length is pinned from BOTH ends: the largest starting cursor
    # any template carries ($8C -> 36 longwords) and the next template's base.
    cur = max(u16(d, t + 0x0E) for t in tpls)
    if 0x28A5C2 + (cur // 4 + 1) * 4 != 0x28A652:
        raise SystemExit(
            f"$28A5C2 + (${cur:04X}/4 + 1) longwords does not land on $28A652, "
            f"the first template of the run. The descriptor list and the "
            f"templates no longer abut.")
    # $28ABE0's draw table: `moveq #$3f` -> 64 bytes, and $28AC3A is code.
    if d[0x28AC3A:0x28AC40] != bytes((0x41, 0xF9, 0x00, 0x81, 0xDB, 0x90)):
        raise SystemExit("$28ABFA's 64-byte draw table does not end at $28AC3A "
                         "(`lea $81DB90,A0`).")


def walk_effect_script(d: bytes, desc: int, dur: int) -> tuple[list[int], int, int]:
    """W54.  Walk ONE effect script the way `$288E4E` + `$288E20` walk it.

    One stream address per duration word, until the duration list's `$FFFF`.
    A descriptor list is 4-byte stream addresses interleaved with 8-byte
    NEGATIVE-tagged escape commands (`$288E26 bpl` is the discriminator), and
    both commands are 8 bytes whichever arm they take.

    Returns (streams, descriptor-list end, duration-list end).
    """
    streams: list[int] = []
    dc, du = desc, dur
    for _ in range(200):
        w = u16(d, du)
        du += 2
        if w == 0xFFFF:
            break
        for _ in range(64):
            v = u32(d, dc)
            if not v & 0x80000000:
                break
            dc += 8
        else:
            raise SystemExit(f"$288E20's walk ran away at ${dc:06X}")
        streams.append(u32(d, dc))
        dc += 4
    else:
        raise SystemExit(f"effect script ${desc:06X}/${dur:06X} has no $FFFF "
                         f"terminator within 200 cells")
    return streams, dc, du


def check_pool_b_extents(d: bytes) -> None:
    """W54 (E5b).  ASSERT POOL B's SCRIPT BLOCK AGAINST THE CARTRIDGE, every export.

    The $221520 window is 4,344 bytes claimed by ONE line in SHOT_WINDOWS, and a
    wrong extent there ships a truncated script -- which does not throw, it draws
    the wrong picture and then reads a duration word out of whatever follows.
    So every number that line rests on is re-derived here from the image:

      * the two tables ABUT ($221520 + 34*8 == $221630) and the second one abuts
        THE DATA ($221630 + 34*8 == $221740 == entry [0][0]'s own list);
      * walking all 68 entries in lockstep reaches exactly the window's far end;
      * and the two remap rows are pinned by what FOLLOWS them -- `4E75` (rts)
        after $267FA0's three rows, and a sprite stream address after $278320's
        two.  Neither is a comment: both are read out of `d`.
    """
    TA, TB, DATA = 0x221520, 0x221630, 0x221740
    N, WIN_END = 34, 0x222618
    if TA + N * 8 != TB or TB + N * 8 != DATA:
        raise SystemExit(
            f"the effect script tables no longer abut: ${TA:06X} + {N}*8 = "
            f"${TA + N * 8:06X} (want ${TB:06X}) and ${TB:06X} + {N}*8 = "
            f"${TB + N * 8:06X} (want ${DATA:06X}).")
    if u32(d, TA) != DATA:
        raise SystemExit(
            f"$221520[0]'s descriptor list is ${u32(d, TA):06X}, not ${DATA:06X}. "
            f"The table's far end is pinned by entry [0][0] pointing AT the "
            f"data that follows it, and that has stopped being true.")
    hi, scripts, streams = 0, set(), set()
    for tbl in (TA, TB):
        for i in range(N):
            desc, dur = u32(d, tbl + i * 8), u32(d, tbl + i * 8 + 4)
            ss, dce, due = walk_effect_script(d, desc, dur)
            if len(ss) != (due - dur - 2) // 2:         # one stream per duration
                raise SystemExit(
                    f"effect entry ${tbl:06X}[{i}]: {len(ss)} streams against "
                    f"{(due - dur - 2) // 2} duration words. The two lists are "
                    f"walked in LOCKSTEP and must end together.")
            scripts.add((desc, dur))
            streams.update(ss)
            hi = max(hi, dce, due)
    if hi != WIN_END:
        raise SystemExit(
            f"walking all {2 * N} effect script entries reaches ${hi:06X}; "
            f"this file's $221520 window ends at ${WIN_END:06X}. A SHORT window "
            f"is a truncated script -- it draws the wrong cell and then reads a "
            f"duration word out of whatever follows.")
    if len(scripts) != 23 or len(streams) != 269:
        raise SystemExit(
            f"the {2 * N} effect entries resolve to {len(scripts)} distinct "
            f"scripts over {len(streams)} distinct streams; W54 measured 23 and "
            f"269 (reproducing 50-recon-effects 5.1 exactly).")
    # AND THE DECLARED WINDOW MUST COVER EXACTLY THAT.  Without this the walk
    # above proves where the data ends and the SHOT_WINDOWS line beside it can
    # still claim any length it likes -- and a SHORT window does not throw at
    # the export, it throws on the player's machine, on whichever frame first
    # reaches the last script.  Both numbers come out of variables here.
    declared = [(a, ln) for a, ln, _ in SHOT_WINDOWS if a == TA]
    if len(declared) != 1 or declared[0][1] != WIN_END - TA:
        raise SystemExit(
            f"SHOT_WINDOWS declares {declared} for ${TA:06X}; walking all "
            f"{2 * N} script entries says it must be ${WIN_END - TA:04X} bytes "
            f"(${TA:06X}..${WIN_END - 1:06X}). A SHORT window is not caught at "
            f"the export -- it is caught by src/rom.js on a player's machine.")
    if d[0x267FC4:0x267FC6] != b"\x4e\x75":
        raise SystemExit(
            f"$267FA0's three 6-word remap rows should end at $267FC4 with "
            f"`4E75` (rts); the image has {d[0x267FC4:0x267FC6].hex()}. A row "
            f"that runs on lands a wrong value in ($1e,A0), which $288FE4 jsrs.")
    if u32(d, 0x278338) & 0xFF000000 or u32(d, 0x278338) < 0x100000:
        raise SystemExit(
            f"$278320's two remap rows should end at $278338 with a sprite "
            f"STREAM address; the image has ${u32(d, 0x278338):08X}.")


def check_item_extents(d: bytes) -> None:
    """W61 (I2).  ASSERT THE ITEM FAMILY'S GEOMETRY AGAINST THE CARTRIDGE.

    Six things `src/items.js` rests on are not checkable from inside the port:
    the six pool bases, the 25-slot total, both dispatch tables' extents, the
    26-byte template stride, the collision half-extents and the two
    collected-animation lengths.  Each is re-derived here from the image, so a
    cartridge that disagrees stops the EXPORT rather than the player's machine.
    """
    # 1. THE SIX POOLS CLOSE EXACTLY ON THE LIVE COUNT WORD.
    pools = [(0x00, 0x816B7A, 7), (0x04, 0x816D7A, 1), (0x08, 0x816DFA, 1),
             (0x0C, 0x816E7A, 5), (0x14, 0x816FFA, 5), (0x10, 0x81717A, 0)]
    at = 0x816B7A
    for d0, base, dbra in pools:
        if at != base:
            raise SystemExit(
                f"the item pools no longer abut: kind ${d0:02X} should start at "
                f"${at:06X} and src/items.js says ${base:06X}.")
        at += (dbra + 1) * 0x40
    if at != 0x8171BA:
        raise SystemExit(
            f"the six item pools total ${at - 0x816B7A:X} bytes and end at "
            f"${at:06X}; $27F6DC's live count is $8171BA. 25 x $40 == $640.")
    # $27E990 `move.w #$321,D0` + the dbra's own pass = $322 words = 1,604 B =
    # the 25 slots PLUS $8171BA PLUS $8171BC.  If that stops being true the
    # clear leaves a live record or a stale variant counter behind.
    if u16(d, 0x27E992) != 0x0321:
        raise SystemExit(
            f"$27E990 move.w #$321,D0 -- the item family's clear -- now reads "
            f"#${u16(d, 0x27E992):04X}. It must cover 25 slots + $8171BA + "
            f"$8171BC = $322 words.")
    if (0x321 + 1) * 2 != (0x8171BE - 0x816B7A):
        raise SystemExit("the item clear no longer reaches $8171BE.")
    # 2. BOTH DISPATCH TABLES, AND BOTH RUN OFF THE END INTO CODE.
    disp = [u32(d, 0x27E9F8 + 4 * i) for i in range(8)]
    want = [0x27EA2A, 0x27EBDC, 0x27ED8C, 0x27EF50,
            0x27F1A6, 0x27F254, 0x27F2F0, 0x27EA18]
    if disp != want:
        raise SystemExit(
            "$27E9F8's eight entries are "
            + " ".join(f"${x:06X}" for x in disp)
            + "; src/items.js DISPATCH says "
            + " ".join(f"${x:06X}" for x in want))
    if d[0x27EA18:0x27EA1A] != b"\x4e\x75":
        raise SystemExit(
            f"$27E9F8[7] points at $27EA18, which must BE the `rts` (4E75); the "
            f"image has {d[0x27EA18:0x27EA1A].hex()}. Entry [7] is a deliberate "
            f"no-op, and if it stops being one the driver jsrs into data.")
    tmpl = [u32(d, 0x27F746 + 4 * i) for i in range(8)]
    twant = [0x27F766, 0x27F780, 0x27F79A, 0x27F7B4,
             0x27F7CE, 0x27F7B4, 0x27F7E8, 0x27F7E8]
    if tmpl != twant:
        raise SystemExit(
            "$27F746's eight entries are "
            + " ".join(f"${x:06X}" for x in tmpl)
            + "; src/items.js TEMPLATES says "
            + " ".join(f"${x:06X}" for x in twant))
    for i in range(4):
        if twant[i + 1] - twant[i] != 26:
            raise SystemExit(
                f"template {i} at ${twant[i]:06X} is "
                f"{twant[i + 1] - twant[i]} bytes, not the 26 that $27F6C8's "
                f"six longs and one word copy.")
    if d[0x27F7E8:0x27F7EA] != b"\x4e\x75":
        raise SystemExit(
            f"$27F746[6] and [7] point at $27F7E8, which this port relies on "
            f"being CODE (`rts`, 4E75) so that its range check has something to "
            f"be right about; the image has {d[0x27F7E8:0x27F7EA].hex()}.")
    # 3. THE COLLISION HALF-EXTENTS ARE $0600 x $0600 FOR EVERY KIND, which is
    #    what `$244D62`'s block 2 reads at +$10/+$12.  A template that stopped
    #    carrying them would make every item uncollectable and nothing in the
    #    port could tell.
    for i, t in enumerate(twant[:5]):
        if u16(d, t + 0x0A) != 0x0600 or u16(d, t + 0x0C) != 0x0600:
            raise SystemExit(
                f"template {i} at ${t:06X} carries half-extents "
                f"${u16(d, t + 0x0A):04X} x ${u16(d, t + 0x0C):04X}, not "
                f"$0600 x $0600. Block 2 reads them at +$10/+$12.")
    # 4. THE TWO COLLECTED-ANIMATION LENGTHS, pinned by the STEPPERS' OWN
    #    `cmpi.w`, and the five lists closing on the collect tail.
    if 0x27F500 + 8 + 17 * 4 != 0x27F54C:
        raise SystemExit(
            "$27F500 + 8 + 17*4 must land on $27F54C, THE COLLECT TAIL.")
    if u16(d, 0x27F64C) != 0x0078 or u16(d, 0x27F6A4) != 0x0044:
        raise SystemExit(
            f"the collected-animation steppers' own bounds are now "
            f"${u16(d, 0x27F64C):04X} and ${u16(d, 0x27F6A4):04X}; src/items.js "
            f"ANIM_END says $78 and $44, and those two immediates are the ONLY "
            f"things that pin the list lengths.")
    # 5. THE TWELVE POWER LISTS ARE FIVE WORDS EACH, and the array of twelve
    #    pointers holds exactly those twelve addresses.  This is what makes
    #    "five power levels" a fact about the cartridge and not a reading.
    #
    # AND THE ARRAY IS **INTERLEAVED**, which recon 59 §9.6 could not settle and
    # which this check found by being wrong first.  The twelve pointers are NOT
    # $25523C..$2552AA in order: entry [2n] is the SHOT list (the first six,
    # $25523C + 10n) and entry [2n+1] is the LASER list (the second six,
    # $255278 + 10n).  That is exactly why `$252CEC movea.l ($4,A0,D0.w),A1`
    # and `$252CF4 movea.l (A0,D0.w),A0` read TWO entries 4 bytes apart, and it
    # is what makes the row index having to be EVEN a fact rather than a
    # precaution -- an odd row pairs a shot list with the NEXT row's shot list.
    #
    # [M] it also corroborates both of the port's own measured cursors from the
    # other side: `src/options.js` measured $8127E8 = $255278, which is entry
    # [1] -- row 0's LASER list -- and `src/shots.js` measured the word behind
    # $8127E4 as 4, which is $25523C's word[0], row 0's SHOT list.  Two
    # independent RAM measurements landing on the two halves of ONE row.
    ptrs = [u32(d, 0x25520C + 4 * i) for i in range(12)]
    want_ptrs = []
    for r in range(6):
        want_ptrs.append(0x25523C + 10 * r)      # the SHOT list
        want_ptrs.append(0x255278 + 10 * r)      # ...and the LASER list beside it
    if ptrs != want_ptrs:
        raise SystemExit(
            "$25520C's twelve longwords are no longer six INTERLEAVED "
            "(shot, laser) pairs over the five-word lists $25523C..$2552B3: "
            + " ".join(f"${x:06X}" for x in ptrs))
    if 0x25523C + 12 * 10 != 0x2552B4:
        raise SystemExit("twelve five-word lists is not 120 bytes.")
    declared = [(a, ln) for a, ln, _ in SHOT_WINDOWS if a == 0x255200]
    if not declared or 0x255200 + declared[0][1] < 0x2552B4:
        raise SystemExit(
            f"the $255200 window is {declared} and must reach $2552B4 -- the "
            f"power cursors $8127E4/$8127E8 walk to word[4] of the LAST list.")


def check_hud_extents(d: bytes) -> None:
    """W63 (B1).  ASSERT OBJECT TYPE 0's THREE TABLES AGAINST THE CARTRIDGE.

    None of these is checkable from inside the port, and all three are the kind
    of extent `docs/knowledge/09` says to derive from the listing rather than
    from a run -- a SHORT window is not caught at the export, it is caught on a
    player's machine, which is W54 6.2's own lesson stated twice.
    """
    # 1. $285F52's INDEX WRAP names the last entry, and $287ECA abuts it.
    #    $285F80 move.w #$38,$81B59A -- byte offset $38 = entry [14].
    if u16(d, 0x285F82) != 0x0038:
        raise SystemExit(
            f"$285F80 move.w #$38,$81B59A -- $285F52's cursor wrap -- now reads "
            f"#${u16(d, 0x285F82):04X}. The $287E8E table's extent is derived "
            f"from it (last entry = wrap/4).")
    if 0x287E8E + (0x38 + 4) != 0x287ECA:
        raise SystemExit(
            "$287E8E + 15 longwords != $287ECA, so the two cursor tables no "
            "longer abut and the first one's extent is unpinned.")
    # $285F78 subq.w #$4 -- the STRIDE the wrap is divided by.
    if d[0x285F78] != 0x59 or d[0x285F79] != 0x79:
        raise SystemExit("$285F78 is no longer `subq.w #$4,$81B59A`.")
    # 2. $285F8A's index space is the WHOLE $00..$FC: `moveq #$3F,D0 / and.w
    #    $80390A,D0 / add.w D0,D0 / add.w D0,D0`.
    if d[0x285F8A] != 0x70 or d[0x285F8B] != 0x3F:
        raise SystemExit("$285F8A is no longer `moveq #$3F,D0`, so $287ECA's "
                         "64-entry extent is no longer derived from the mask.")
    declared = [(a, ln) for a, ln, _ in SHOT_WINDOWS if a == 0x287E8E]
    if not declared or 0x287E8E + declared[0][1] < 0x287FCA:
        raise SystemExit(
            f"the $287E8E window is {declared} and must reach $287FCA -- "
            f"$287ECA + 64 longwords. A SHORT window is not caught here, it is "
            f"caught by src/rom.js on a player's machine.")
    # 3. $28840E: FOUR extend intervals, terminator at the index $286FFE names.
    if u16(d, 0x287000) != 0x000C:
        raise SystemExit(
            f"$286FFE move.w #$C,(A4) -- the extend cursor's last index -- now "
            f"reads #${u16(d, 0x287000):04X}; $28840E's extent comes from it.")
    if u32(d, 0x28840E + 0x0C) != 0xFFFFFFFF:
        raise SystemExit(
            f"$28840E[3] is ${u32(d, 0x28840E + 0x0C):08X} and must be "
            f"$FFFFFFFF -- $286FE8 tests for it as the `no more extends` mark.")
    if u32(d, 0x28840E + 0x10) != 0x41F90080:
        raise SystemExit(
            f"$28840E[4] is ${u32(d, 0x28840E + 0x10):08X}; it must be the "
            f"`lea $803824,A0` that proves the table is FOUR entries and the "
            f"fifth longword is CODE.")
    if 0x2883FE + 0x10 != 0x28840E:
        raise SystemExit("$2883FE (the FIRST-threshold table $286FCC indexes by "
                         "the same DIP) no longer abuts $28840E.")


def check_boss_a4_extent(d: bytes) -> None:
    """W64 (B2).  W62's `$294F68` window was FIVE pairs and the table is SEVEN.

    Not this wave's table -- but this wave's bomb is what reached entry [5],
    and a short window is a throw on a player's machine rather than a failure
    here.  The extent is pinned from ABOVE by the first longword that decodes
    as an instruction, exactly as `$28840E`'s is.
    """
    for i in (5, 6):
        v = u32(d, 0x294F68 + i * 8)
        if not 0x295000 <= v < 0x296000:
            raise SystemExit(
                f"$294F68[{i}] is ${v:08X} and must be a $295xxx script "
                f"pointer -- the seven-pair extent is derived from it.")
    if u32(d, 0x294F68 + 7 * 8) != 0x397C00C0:
        raise SystemExit(
            f"$294F68[7] is ${u32(d, 0x294F68 + 7 * 8):08X}; it must be the "
            f"`move.w #$C0,...` that proves the table is SEVEN pairs and the "
            f"eighth longword is CODE.")
    declared = [(a, ln) for a, ln, _ in SHOT_WINDOWS if a == 0x294F68]
    if not declared or declared[0][1] < 0x38:
        raise SystemExit(
            f"the $294F68 window is {declared} and must be at least $38 -- "
            f"seven {{init,step}} pairs. W62 declared $28 and [M] W64 reached "
            f"entry [5] at lf9153 of a run that bombs.")


def check_boss_script_table_extents(d: bytes) -> None:
    """W82.  THE A3 AND A1 SCRIPT TABLES, WHOSE WINDOWS WERE SHORT AND ABSENT.

    Same lesson as `check_boss_a4_extent`, arriving for the third time on the
    same boss: a table is indexed by the SCRIPT ID, which is a byte, and NOT by
    the slot count.  W62 sized `$29370A` at ten because there are ten A3 slots.
    Both far ends are pinned by the `clr.w (a4) / rts` tail that recon 48 1.4
    names -- an INSTRUCTION, read here out of the image rather than trusted.
    """
    DONE_TAIL = 0x42544E75                 # `clr.w (a4)` + `rts`
    for base, pairs, name in ((0x29370A, 21, "A3"), (0x295856, 15, "A1")):
        for i in range(pairs):
            for half, off in (("init", 0), ("step", 4)):
                v = u32(d, base + i * 8 + off)
                if not 0x292000 <= v < 0x297000:
                    raise SystemExit(
                        f"${base:06X}[{i}].{half} is ${v:08X} and must be a "
                        f"boss-local pointer -- the {pairs}-pair extent of the "
                        f"{name} table is derived from it.")
        end = u32(d, base + pairs * 8)
        if end != DONE_TAIL:
            raise SystemExit(
                f"${base:06X}[{pairs}] is ${end:08X}; it must be ${DONE_TAIL:08X} "
                f"(`clr.w (a4) / rts`), the CODE that proves the {name} table is "
                f"{pairs} pairs and not more.")
        want = pairs * 8
        declared = [(a, ln) for a, ln, _ in SHOT_WINDOWS if a == base]
        if not declared or declared[0][1] < want:
            raise SystemExit(
                f"the ${base:06X} window is {declared} and must be at least "
                f"${want:X} -- {pairs} {{init,step}} pairs. A SHORT window here "
                f"makes an unported script throw naming the TABLE instead of "
                f"naming itself.")


def check_boss_object_tables(d: bytes) -> None:
    """W82.  THE THREE OBJECT-ROUTINE SPRITE TABLES.

    Every extent below is pinned by the first instruction PAST the table, and
    that instruction is the next OBJECT routine's own entry point -- which the
    A2 list at `$292932` names.  So the pins are not a reading of the data: they
    are longwords the cartridge itself publishes as routine addresses.
    """
    # $292932's seven longwords are the pins.  Read them rather than assume.
    objs = [u32(d, 0x292932 + i * 4) for i in range(7)]
    if objs != [0x292972, 0x292B08, 0x292952, 0x292BFA,
                0x292E0A, 0x292E3E, 0x292F4A]:
        raise SystemExit(
            f"the A2 OBJECT list $292932 reads {[f'${v:06X}' for v in objs]}; "
            f"W82's three table extents are pinned by entries [4] $292E0A, "
            f"[5] $292E3E and [6] $292F4A and cannot be derived if it moved.")
    for base, end, why in ((0x292C2A, objs[4], "OBJECT 3's 15 rows of $20"),
                           (0x292E32, objs[5], "OBJECT 4's three longwords"),
                           (0x292ECA, objs[6], "OBJECT 5's 32 longwords")):
        want = end - base
        declared = [(a, ln) for a, ln, _ in SHOT_WINDOWS if a == base]
        if not declared or declared[0][1] != want:
            raise SystemExit(
                f"the ${base:06X} window is {declared} and must be exactly "
                f"${want:X} -- {why}, pinned from above by ${end:06X}.")
    # $292BFA's bias: `addq.w #$7` before the `lsl.w #$5`, so row 0 is $AC = -7
    # and the `lea` address is the BOTTOM of the table.  If that byte changed,
    # every row index below is off by a multiple of $20.
    if d[0x292C04:0x292C08] != bytes((0x5E, 0x42, 0xEB, 0x4A)):
        raise SystemExit(
            "$292C04 is no longer `addq.w #$7,D2 / lsl.w #$5,D2`; OBJECT 3's "
            "table base and its SIGNED $AC range are derived from that bias.")


def check_bomb_extents(d: bytes) -> None:
    """W64 (B2).  ASSERT THE BOMB'S SIX EXTENTS AGAINST THE CARTRIDGE.

    None of these is checkable from inside the port: a SHORT window is not
    caught at the export, it is caught by `src/rom.js` on a player's machine
    (W54 6.2, and W63 9b made it a rule).  Every assertion below reads either
    an INSTRUCTION that produces the extent or the TERMINATOR that ends it.
    """
    # 1. The window must cover all six, i.e. reach $25664E.
    declared = [(a, ln) for a, ln, _ in SHOT_WINDOWS if a == 0x25653C]
    if not declared or 0x25653C + declared[0][1] < 0x25664E:
        raise SystemExit(
            f"the $25653C window is {declared} and must reach $25664E -- "
            f"$25663A + four longwords + the $FFFFFFFF terminator.")
    # 2. $255E52 is `lea $25653C,A0`, i.e. the init template's ADDRESS is in
    #    the instruction and not in this file.
    if u32(d, 0x255E54) != 0x0025653C:
        raise SystemExit(
            f"$255E52 lea now reads ${u32(d, 0x255E54):08X}; the init "
            f"template's address comes from that instruction.")
    # 3. ...and the SCRIPT POINTER is the long at template offset $10.
    if u32(d, 0x25653C + 0x10) != 0x00256558:
        raise SystemExit(
            f"$25653C[+$10] is ${u32(d, 0x25653C + 0x10):08X}; it must be "
            f"$00256558 -- the long the init install drops on ($1E,A6).")
    # 4. FOUR script entries of 12 bytes and then $FFFF, which is what makes
    #    the phase-0 extent 50 bytes rather than "whatever a run walked".
    if u16(d, 0x256558 + 4 * 12) != 0xFFFF:
        raise SystemExit(
            f"$256558 + 4*12 is ${u16(d, 0x256558 + 4 * 12):04X} and must be "
            f"$FFFF -- $255EC6 cmpi.w #$FFFF,(A0) is the only terminator.")
    # 5. $2565BC's and $25661E's addresses come from their own `lea`s.
    if u32(d, 0x255ED4) != 0x002565BC:
        raise SystemExit(f"$255ED2 lea now reads ${u32(d, 0x255ED4):08X}.")
    if u32(d, 0x255F50) != 0x0025661E:
        raise SystemExit(f"$255F4E lea now reads ${u32(d, 0x255F50):08X}.")
    # 6. THE FADE's index space.  $2565BC[+$14] is the table and the WORD at
    #    +$16 of the same template is ($24,A6)'s seed, $1C -- eight longwords.
    if u32(d, 0x2565BC + 0x14) != 0x002565DE:
        raise SystemExit(
            f"$2565BC[+$14] is ${u32(d, 0x2565BC + 0x14):08X}; it must be "
            f"$002565DE, the fade's anim table.")
    if u16(d, 0x2565BC + 0x1A) != 0x001C:
        raise SystemExit(
            f"$2565BC[+$1A] -- the word the install drops on ($24,A6) -- is "
            f"${u16(d, 0x2565BC + 0x1A):04X} and must be $1C. The $2565DE "
            f"table's EIGHT longwords are derived from it, together with "
            f"$255F32 subq.w #$4.")
    if d[0x255F32] != 0x59 or d[0x255F33] != 0x6E:
        raise SystemExit("$255F32 is no longer `subq.w #$4,($24,A6)`, so the "
                         "$2565DE table's stride is no longer derived.")
    # 7. THE BLINK's list ends at the FIRST $FFFFFFFF, and $255F94 is the
    #    instruction that says so.
    if u32(d, 0x25661E + 0x14) != 0x0025663A:
        raise SystemExit(
            f"$25661E[+$14] is ${u32(d, 0x25661E + 0x14):08X}; it must be "
            f"$0025663A.")
    if u32(d, 0x25663A + 4 * 4) != 0xFFFFFFFF:
        raise SystemExit(
            f"$25663A + 4 longwords is ${u32(d, 0x25663A + 4 * 4):08X} and "
            f"must be $FFFFFFFF -- $255F94 cmpi.l is the terminator.")


def s16(v: int) -> int:
    """A 16-bit value as a signed displacement (PC-relative `lea`s use one)."""
    return v - 0x10000 if v >= 0x8000 else v


def check_beam_bomb_extents(d: bytes) -> None:
    """W65 (B3).  ASSERT THE LASER BOMB'S EXTENTS AGAINST THE CARTRIDGE.

    Same rule as `check_bomb_extents`: a unit test can only read this file's
    source, so every number the port depends on is re-derived here from the
    INSTRUCTION or the TERMINATOR that produces it, against the real image, on
    every export.  W54 6.2 -- a short window is caught on a player's machine.
    """
    # 1. $255FEA is `lea $256CAA,A0`, so the install template's address is in
    #    the instruction and not in this file.
    if u32(d, 0x255FEC) != 0x00256CAA:
        raise SystemExit(f"$255FEA lea now reads ${u32(d, 0x255FEC):08X}; the "
                         f"LASER BOMB's install template comes from it.")
    # 2. ...and $2561DE/$256270/$2563EA are all `lea $256D48,A2`, the ONE
    #    segment template three loops share.
    for at in (0x2561E0, 0x256272, 0x2563EC):
        if u32(d, at) != 0x00256D48:
            raise SystemExit(
                f"the segment-template `lea` at ${at - 2:06X} reads "
                f"${u32(d, at):08X} and must be $00256D48.")
    # 3. THE INSTALL IS 158 BYTES, i.e. it ends exactly where $256D48 begins.
    #    Derived by replaying the copy sequence's sizes, which is the only
    #    honest way to get it: 12 moves (4,2,4,4,4,2,4,4,2,4,4 == 38 with the
    #    two `addq` holes skipped) and then three record blocks.
    seq = ([4, 2, 4, 4, 4, 2, 4, 4, 2, 4, 4]
           + [2, 4, 2, 4, 4, 4, 2, 4, 4, 4, 4, 2]
           + [2, 4, 2, 4, 4, 4, 2, 4, 4, 2, 4, 4]
           + [2, 4, 2, 4, 4, 4, 2, 4, 4, 4, 4, 2])
    if 0x256CAA + sum(seq) != 0x256D48:
        raise SystemExit(
            f"the $255FEA install sequence consumes {sum(seq)} bytes, so it "
            f"ends at ${0x256CAA + sum(seq):06X} and not at $256D48. Either "
            f"the sequence changed or src/bomb.js `installBeamTemplate` is "
            f"out of step with it.")
    # 4. THE FOUR SCRIPT POINTERS the install drops on the four heads.  They
    #    are longs INSIDE the template, at the offsets the copy sequence lands
    #    them on, and they are what make $256662..$256691 four 12-byte tables
    #    (three longs each) rather than one long one: consecutive, in the
    #    record order 0 / 42 / 43 / 44, 12 bytes apart, in THAT order.
    heads = [(0x256CAA + 0x14, 0x00256662, "record 0"),
             (0x256CAA + 0x3C, 0x0025667A, "record 42"),
             (0x256CAA + 0x64, 0x0025666E, "record 43"),
             (0x256CAA + 0x8C, 0x00256686, "record 44")]
    for at, want, who in heads:
        if u32(d, at) != want:
            raise SystemExit(
                f"the install template's script pointer for {who} is at "
                f"${at:06X} and reads ${u32(d, at):08X}; it must be "
                f"${want:08X}. src/bomb.js `BEAM_REC` depends on it.")
    if sorted(w for _, w, _ in heads) != [0x256662, 0x25666E, 0x25667A,
                                          0x256686]:
        raise SystemExit("the four head tables are no longer 12 bytes apart.")
    # 5. ($24,A6)'s SEED and its step, which give the head tables THREE entries.
    #    $2560D2 is `subq.w #$4,($24,A6)`; the seed is the install's own long.
    if d[0x2560D2] != 0x59 or d[0x2560D3] != 0x6E:
        raise SystemExit("$2560D2 is no longer `subq.w #$4,($24,A6)`, so the "
                         "head tables' three entries are no longer derived.")
    # 6. $2561AA's cursor: seeded $1C by $2561B0 and stepped `subq.w #$4`,
    #    so $256692 holds EIGHT pointers.
    if u16(d, 0x2561B2) != 0x001C:
        raise SystemExit(
            f"$2561B0 now writes ${u16(d, 0x2561B2):04X} to ($80A,A6); "
            f"$256692's eight entries are derived from $1C and `subq.w #$4`.")
    if d[0x2561AA] != 0x59 or d[0x2561AB] != 0x6E:
        raise SystemExit("$2561AA is no longer `subq.w #$4,($80A,A6)`.")
    # 7. $256712's TWELVE five-longword entries and the terminator $256170
    #    tests.  Walk it here rather than trusting the count.
    a, n = 0x256712, 0
    while u32(d, a) != 0xFFFFFFFF:
        n, a = n + 1, a + 20
        if n > 64:
            raise SystemExit("$256712 has no $FFFFFFFF within 64 entries; "
                             "$256170 cmpi.l is the only terminator.")
    if n != 12 or a != 0x256802:
        raise SystemExit(
            f"$256712 walks {n} entries and terminates at ${a:06X}; it must "
            f"be 12 and $256802.")
    # 8. THE FAR END.  The last entry's fifth long names an eight-pointer
    #    table, and that table's end is the window's end -- pinned by $256986,
    #    which is `$256086 move.l #$256986,($1E,A6)`, the bit-1 twin.
    last = u32(d, 0x256712 + 11 * 20 + 16)
    if last + 32 != 0x256986:
        raise SystemExit(
            f"the last $256712 entry names ${last:06X}, whose eight pointers "
            f"end at ${last + 32:06X}; the window's far end must be $256986.")
    if u32(d, 0x256088) != 0x00256986:
        raise SystemExit(
            f"$256086 now writes ${u32(d, 0x256088):08X}; $256986 is what pins "
            f"the $256662 window's far end.")
    declared = [(a, ln) for a, ln, _ in SHOT_WINDOWS if a == 0x256662]
    if not declared or 0x256662 + declared[0][1] != 0x256986:
        raise SystemExit(
            f"the $256662 window is {declared} and must end exactly at "
            f"$256986.")
    # 9. `$28A030` has THREE entries because `$28A03C` is CODE, and $243174's
    #    bytes are 0/1/2 -- the two halves of one claim.
    if u32(d, 0x28A03C) != 0x48E7FFFE:
        raise SystemExit(
            f"$28A03C is ${u32(d, 0x28A03C):08X} and must be $48E7FFFE "
            f"(`movem.l D0-D7/A0-A6,-(A7)`, i.e. $289FF4 itself). $28A030's "
            f"THREE entries are derived from it.")
    bad = sorted(set(d[0x243174:0x243174 + 128]) - {0, 1, 2})
    if bad:
        raise SystemExit(
            f"$243174 holds {bad} as well as 0/1/2, so $28A000's `add.w D0,D0` "
            f"twice can index past $28A030's three entries.")
    # 10. $242EC2's table is UNMASKED and $28AB86's is `moveq #$3F`; every far
    #     end is the next `addq.b #1,$803917` in the family, which is the same
    #     way W31 pinned $24324E and $24301A and W53 pinned $28ABFA.
    for tbl, ln, nxt in ((0x242EDE, 0x100, 0x242FDE), (0x28ABA0, 0x40, 0x28ABE0),
                         (0x243174, 0x80, 0x2431F4)):
        if tbl + ln != nxt:
            raise SystemExit(f"${tbl:06X} + ${ln:X} is ${tbl + ln:06X}, not "
                             f"the ${nxt:06X} that pins it.")
        if d[nxt] != 0x52 or d[nxt + 1] != 0x39 or u32(d, nxt + 2) != 0x00803917:
            raise SystemExit(
                f"${nxt:06X} is not `addq.b #1,$803917`, so ${tbl:06X}'s far "
                f"end is no longer pinned by the next RNG entry point.")
    # 11. THE POD KNOCKBACK's two tables, which W65 made reachable by setting
    #     the player's flags bit 7 at $249A92.  $24D282's five words and
    #     $24D28E's twenty ABUT, and $24D2BE is `moveq #$0,D0` -- CODE.
    if u16(d, 0x24D18E) != 0x41FA or 0x24D190 + s16(u16(d, 0x24D190)) != 0x24D28E:
        raise SystemExit(
            f"$24D18E is not `lea ($24D28E,PC),A0`; the ramp's address comes "
            f"from that instruction.")
    if u16(d, 0x24D210) != 0x41FA or 0x24D212 + s16(u16(d, 0x24D212)) != 0x24D282:
        raise SystemExit("$24D210 is not `lea ($24D282,PC),A0`.")
    if d[0x24D19C] != 0x55 or d[0x24D19D] != 0x6E:
        raise SystemExit("$24D19C is no longer `subq.w #$2,($38,A6)`, so the "
                         "$24D28E ramp's 20 entries are no longer derived.")
    if u16(d, 0x249ADA) != 0x0026 or u16(d, 0x249AE0) != 0x0008:
        raise SystemExit(
            f"$249AD8/$249ADE now seed ${u16(d, 0x249ADA):04X}/"
            f"${u16(d, 0x249AE0):04X} into ($38,A1)/($56,A1); the two pod "
            f"tables' index spaces come from those two immediates.")
    # 12. `$289FF4`'s THREE pool-E templates and their three lists, all six
    #     extents derived: 22 bytes per template (the fields $28A1DA reads),
    #     eight longwords per list (the cursor's `$001C` seed and $28A162's
    #     `-4`), and the three list POINTERS are the templates' own +$10 longs.
    for i in range(3):
        t = 0x28A464 + i * 22
        if u32(d, 0x28A030 + i * 4) != t:
            raise SystemExit(
                f"$28A030[{i}] is ${u32(d, 0x28A030 + i * 4):08X} and must be "
                f"${t:06X} -- the templates are 22 bytes apart.")
        if u32(d, t + 0x10) != 0x28A4A6 + i * 32:
            raise SystemExit(
                f"template ${t:06X}'s list pointer is ${u32(d, t + 0x10):08X}, "
                f"not ${0x28A4A6 + i * 32:06X}.")
        if u32(d, t + 0x0C) & 0xFFFF != 0x001C:
            raise SystemExit(
                f"template ${t:06X}'s cursor seed is "
                f"${u32(d, t + 0x0C) & 0xFFFF:04X} and must be $001C -- the "
                f"lists' EIGHT longwords are derived from it.")
    if u32(d, 0x28A506 + 0x10) != 0x28A51C:
        raise SystemExit(
            f"$28A506 is not the next family's template (its +$10 reads "
            f"${u32(d, 0x28A506 + 0x10):08X}, not $0028A51C), so the "
            f"$28A464 window's far end is no longer pinned.")
    if u16(d, 0x24D2BE) != 0x7000:
        raise SystemExit(
            f"$24D2BE is ${u16(d, 0x24D2BE):04X} and must be $7000 "
            f"(`moveq #$0,D0`) -- it is what pins the $24D282 window's end.")


def build(d: bytes) -> dict:
    check_pool_e_extents(d)                    # W53 -- see the function's docstring
    check_pool_b_extents(d)                    # W54 -- see the function's docstring
    check_item_extents(d)                      # W61 -- see the function's docstring
    check_hud_extents(d)                       # W63 -- see the function's docstring
    check_bomb_extents(d)                      # W64 -- ...and this one's
    check_boss_a4_extent(d)                    # W64 -- W62's window was SHORT
    check_boss_script_table_extents(d)         # W82 -- ...and so were A3 and A1
    check_boss_object_tables(d)                # W82 -- the OBJECT sprite tables
    check_beam_bomb_extents(d)                 # W65 -- THE LASER BOMB's
    n = speed_levels(d)
    base = u32(d, SPEED_PTRS)
    levels = speed_index_set(d)
    quads = {}
    for s in levels:
        a = base + QUAD_STRIDE * s
        quads[str(s)] = [[i32(d, a + 8 * i), i32(d, a + 8 * i + 4)]
                         for i in range(QUAD_ENTRIES)]

    def anim(tbl: int, idx: int) -> list[list[int]]:
        # LITERALLY as the ROM addresses it: `move.w ($58,A6),D0 / add.w D0,D0 /
        # movea.l (A0,D0.w),A0`.  Note the consequence, which is why only index
        # 0 is exported: with ($58,A6) = 1 the longword read is at tbl+2 and
        # lands MIDWAY through the first pointer.  The two pointers here are 4
        # bytes apart, so the ship selector must be 0 or 2, not 0 or 1 -- and
        # ($58,A6) was MEASURED to be 0 for TYPE-A over the whole corpus.
        # TYPE-B was never exercised, so the port throws rather than guess.
        ptr = u32(d, tbl + idx * 2)
        return [[u16(d, ptr + t), u16(d, ptr + t + 2)]
                for t in range(TILT_MIN, TILT_MAX + 1, TILT_STEP)]

    return {
        "_note": ("ROM-DERIVED. Regenerate with games/ddpdoj/tools/export-tables.py. "
                  "Never commit this file."),
        "set": "ddpdojblk", "build": "B",
        "image_sha256": hashlib.sha256(d).hexdigest(),
        "dirTable": {"rom": f"${DIR_TABLE:06X}",
                     "bytes": list(d[DIR_TABLE:DIR_TABLE + 16])},
        "foldTable": {"rom": f"${FOLD_TABLE:06X}",
                      "words": [u16(d, FOLD_TABLE + 2 * i) for i in range(256)]},
        "knockback": {"rom": f"${KNOCKBACK:06X}",
                      "words": [u16(d, KNOCKBACK + 2 * i) for i in range(8)]},
        "speed": {"rom": f"${SPEED_PTRS:06X}", "levels": n,
                  "quadBase": f"${base:06X}", "quadStride": QUAD_STRIDE,
                  "quadEntries": QUAD_ENTRIES, "exported": levels,
                  "quads": quads},
        # WAVE 8 -- the shot subsystem.  See SHOT_WINDOWS.
        "rom": {"_note": ("ROM WINDOWS, read by src/rom.js the way the 68000 "
                          "reads them.  A read outside every window is a LOUD "
                          "NAMED THROW carrying the address, never undefined."),
                "windows": [{"base": f"${a:06X}", "len": ln, "why": why,
                             "hex": d[a:a + ln].hex()}
                            for a, ln, why in SHOT_WINDOWS]},
        "shot": {"spawnPtrTables": [f"${a:06X}" for a in SPAWN_PTR_TABLES],
                 "templates": {f"${a:06X}": v
                               for a, v in sorted(spawn_templates(d).items())}},
        "gov": {k: {"rom": f"${a:06X}",
                    "words": [u16(d, a + 2 * i) for i in range(n)]}
                for k, (a, n) in GOV_TABLES.items()},
        # WAVE 12 -- `b` KEPT ITS KEY AND LOST ITS NAME.  $2553CA -> $2553F2 is
        # the ship's X HALF-EXTENTS indexed by the tilt (10-recon-combat §3,
        # `$2459D0 add.w ($14,A4),D2 / sub.w ($16,A4),D3`), not a second
        # animation table.  It is emitted TWICE for one release -- under the old
        # `b` so an unregenerated rip/ still loads, and under `hitX`, which is
        # what src/vectors.js reads -- and the verifier below asserts they are
        # identical.  MEASURED, all 17 entries (+X/-X): (0000,0080) at tilt -$20,
        # (0080,0080) at 0, (0080,0000) at +$20; build A's twin $1549AE holds
        # $00C0 where this holds $0080, which is the Black Label 2/3 hitbox.
        "anim": {"tiltMin": TILT_MIN, "tiltStep": TILT_STEP,
                 "a": {"rom": f"${ANIM_A:06X}", "shipSel0": anim(ANIM_A, 0)},
                 "b": {"rom": f"${ANIM_B:06X}", "shipSel0": anim(ANIM_B, 0)},
                 "hitX": {"rom": f"${ANIM_B:06X}", "reads": "$2459E4/$2459E8",
                          "shipSel0": anim(ANIM_B, 0)}},
        # WAVE 12 -- the OPTION templates, walked the way $24C0D2 walks them.
        "option": {"templateTable": f"${OPT_TEMPLATES:06X}",
                   "formations": list(OPT_FORMATIONS),
                   "templateLen": OPT_TEMPLATE_LEN,
                   "speedIndices": option_speed_indices(d),
                   "templates": {f"${a:06X}": v
                                 for a, v in sorted(option_templates(d).items())}},
    }


def verify(t: dict) -> list[str]:
    """The invariants the PORT depends on.  A table that silently changed shape
    must stop the port, not feed it plausible numbers."""
    bad = []
    dt = t["dirTable"]["bytes"]
    if len(dt) != 16:
        bad.append("dirTable is not 16 bytes")
    for i, v in enumerate(dt):
        if v != 0xFF and (v & 0x07):
            bad.append(f"dirTable[{i}]=${v:02X} is not a multiple of 8")
    fold = t["foldTable"]["words"]
    if len(fold) != 256:
        bad.append("foldTable is not 256 words")
    # the triangle: index a*4 for a in 0..63 must fold into [0, $200]
    for a in range(64):
        if not 0 <= fold[a * 4] <= 0x200:
            bad.append(f"foldTable[{a * 4}]=${fold[a * 4]:04X} escapes the quadrant")
    sp = t["speed"]
    if sp["levels"] < 29:
        bad.append(f"only {sp['levels']} speed levels, but index 28 is MEASURED in "
                   f"use (Button 2 held; see 04-impl worklog)")
    if sp["levels"] >= SCAN_CAP:
        bad.append(f"the $200920 pattern still holds at the scan cap {SCAN_CAP} -- "
                   f"raise it; 'levels' is not the table's end")
    for k, q in sp["quads"].items():
        if len(q) != QUAD_ENTRIES:
            bad.append(f"speed {k}: {len(q)} entries, expected {QUAD_ENTRIES}")
            continue
        if q[0][1] != 0 or q[-1][0] != 0:
            bad.append(f"speed {k}: quadrant does not run (r,0)..(0,r): "
                       f"{q[0]} .. {q[-1]}")
    if sp["quads"]["0"] != [[0, 0]] * QUAD_ENTRIES:
        bad.append("speed level 0 is not all zeros -- it is the game's 'do not move'")
    for lv in sp["exported"]:
        if str(lv) not in sp["quads"]:
            bad.append(f"speed level {lv} is listed as exported and is not present")
    # WAVE 8: the ROM windows must cover every template the spawn walk found,
    # or the port would throw on its first shot on someone else's machine.
    wins = [(int(w["base"].lstrip("$"), 16), w["len"]) for w in t["rom"]["windows"]]

    def covered(a: int, n: int) -> bool:
        return any(b <= a and a + n <= b + ln for b, ln in wins)

    for k, v in t["shot"]["templates"].items():
        a = int(k.lstrip("$"), 16)
        if len(v) != TEMPLATE_LEN:
            bad.append(f"template {k}: {len(v)} bytes, expected {TEMPLATE_LEN}")
        if not covered(a, TEMPLATE_LEN):
            bad.append(f"template {k} is not inside any exported ROM window")
        if str(v[TEMPLATE_SPEED_OFF]) not in sp["quads"]:
            bad.append(f"template {k} wants speed level {v[TEMPLATE_SPEED_OFF]}, "
                       f"which was not exported")
    for w in t["rom"]["windows"]:
        if len(w["hex"]) != w["len"] * 2:
            bad.append(f"ROM window {w['base']} is {len(w['hex']) // 2} bytes, "
                       f"the manifest says {w['len']}")
    for k, (a, n) in GOV_TABLES.items():
        if len(t["gov"][k]["words"]) != n:
            bad.append(f"gov table {k} is not {n} words")
    for k in ("a", "b", "hitX"):
        n = len(t["anim"][k]["shipSel0"])
        if n != (TILT_MAX - TILT_MIN) // TILT_STEP + 1:
            bad.append(f"anim {k}: {n} tilt entries, expected 17")
    if t["anim"]["hitX"]["shipSel0"] != t["anim"]["b"]["shipSel0"]:
        bad.append("anim.hitX and the legacy anim.b disagree -- they are the "
                   "same $2553F2 read twice and must stay byte-identical")
    # WAVE 12: the ship's X half-extents are a MONOTONE pair over the tilt --
    # +X grows from 0 to $80 as the tilt goes -$20..0 and -X shrinks $80..0 as it
    # goes 0..+$20 -- and both are 0 at exactly one end.  This is the shape the
    # port's `anim()` indexing depends on, and it is asserted rather than
    # assumed: a table that changed shape must stop the export, not feed the
    # collision test plausible numbers.
    hx = t["anim"]["hitX"]["shipSel0"]
    mid = len(hx) // 2
    if hx[mid] != [0x80, 0x80]:
        bad.append(f"anim.hitX at tilt 0 is {hx[mid]}, expected [128, 128] -- "
                   f"the BLACK LABEL 4-px-wide box (build A's $1549AE has "
                   f"[192, 192], the 6-px original)")
    if hx[0][0] != 0 or hx[-1][1] != 0:
        bad.append(f"anim.hitX ends are {hx[0]} .. {hx[-1]}, expected the +X "
                   f"half to start at 0 and the -X half to end at 0")
    # ...and the option templates must be inside a window, same rule as wave 8's.
    for k, v in t["option"]["templates"].items():
        a = int(k.lstrip("$"), 16)
        if len(v) != OPT_TEMPLATE_LEN:
            bad.append(f"option template {k}: {len(v)} bytes, expected "
                       f"{OPT_TEMPLATE_LEN}")
        if not covered(a, OPT_TEMPLATE_LEN):
            bad.append(f"option template {k} is not inside any exported window")
    for lv in t["option"]["speedIndices"]:
        if str(lv) not in sp["quads"]:
            bad.append(f"option template wants speed level {lv}, not exported")
    # ----------------------------------------------------------- WAVE 21
    # The four bullet tables, checked through the EXPORTED BYTES rather than
    # through the image, so a window that is short or misaligned fails HERE and
    # not on a player's machine.  Every check is a property the port depends on
    # and none of them is "the numbers I happened to read".
    def win(a: int, n: int) -> bytes | None:
        for w in t["rom"]["windows"]:
            b = int(w["base"].lstrip("$"), 16)
            if b <= a and a + n <= b + w["len"]:
                o = (a - b) * 2
                return bytes.fromhex(w["hex"][o:o + n * 2])
        return None

    def w16(a):
        b = win(a, 2)
        return None if b is None else struct.unpack(">H", b)[0]

    def w32(a):
        b = win(a, 4)
        return None if b is None else struct.unpack(">I", b)[0]

    tps = [w32(0x281956 + 4 * k) for k in range(39)]
    if any(p is None for p in tps):
        bad.append("the $281956 template pointer table is not fully inside a window")
    else:
        if w32(0x281956 + 4 * 39) != 0x018100:
            bad.append(f"$281956[39] is ${w32(0x281956 + 4 * 39):08X}, expected "
                       f"$00018100 -- the table's far end has moved and the "
                       f"39-kind extent is no longer pinned")
        for k, p in enumerate(tps):
            if win(p, 0x12) is None:
                bad.append(f"template {k} at ${p:06X} is not inside a window")
            elif w16(p + 0x0E) != 20:
                bad.append(f"template {k} base speed is {w16(p + 0x0E)}, not 20 -- "
                           f"all 39 are 20 and src/bullets.js's speed arithmetic "
                           f"starts from that")
            elif (w16(p) & 0x3F) != k and k not in (14, 15):
                bad.append(f"template {k}'s type word ${w16(p):04X} has low 6 bits "
                           f"{w16(p) & 0x3F}; only kinds 14 and 15 are aliases "
                           f"(both carry $810A)")
    for k in range(39):
        for name, base in (("spawn-init", 0x2815C6), ("behaviour", 0x282030)):
            v = w32(base + 4 * k)
            if v is None or not (0x200000 <= v < 0x2B0000):
                bad.append(f"{name}[{k}] = {v} is missing or not a code pointer")
    fold = [w16(0x283F50 + 2 * i) for i in range(256)]
    if any(v is None for v in fold):
        bad.append("the $283F50 fold table is not fully inside a window")
    else:
        for i, v in enumerate(fold):
            m = i % 128
            want = 8 * (m if m <= 64 else 128 - m)
            if v != want:
                bad.append(f"$283F50[{i}] = {v}, expected 8*triangle = {want}")
                break
    vbase = w32(0x200920)
    for s in (0, 1, 20, 128, 255):
        if w32(0x200920 + 4 * s) != vbase + QUAD_STRIDE * s:
            bad.append(f"$200920[{s}] is not ${vbase:06X} + ${QUAD_STRIDE:X}*{s}")
    if win(vbase, 256 * QUAD_STRIDE) is None:
        bad.append("the 256 velocity quadrant tables are not fully inside a window")
    else:
        # every row runs (r,0) at quarter-angle 0 to (0,r) at 64, and speed 0 is
        # a real "do not move".  A short window would show up as a row of zeros
        # in the middle, which this catches and a length check would not.
        for s in (1, 20, 255):
            a = vbase + QUAD_STRIDE * s
            if w32(a + 4) != 0 or w32(a + 8 * 64) != 0:
                bad.append(f"velocity row {s} does not run (r,0)..(0,r)")
        if any(w32(vbase + 4 * i) != 0 for i in range(2 * QUAD_ENTRIES)):
            bad.append("velocity speed level 0 is not all zeros")
    return bad


def main() -> int:
    if not IMAGE.exists():
        raise SystemExit(f"{IMAGE} missing -- run `python tools/oracle/derive.py` first")
    d = IMAGE.read_bytes()
    t = build(d)
    bad = verify(t)
    for b in bad:
        print("FAIL " + b, file=sys.stderr)
    if bad:
        return 1
    print(f"  image sha256 {t['image_sha256']}")
    print(f"  dirTable   {' '.join(f'{b:02x}' for b in t['dirTable']['bytes'])}")
    print(f"  speed      {t['speed']['levels']} levels at {t['speed']['quadBase']}"
          f" stride ${t['speed']['quadStride']:X}, {QUAD_ENTRIES} entries each; "
          f"{len(t['speed']['exported'])} EXPORTED "
          f"{t['speed']['exported'][:34]}{' ...' if len(t['speed']['exported']) > 34 else ''}")
    for s in (0, 1, 22, 28, 80, 232):
        q = t["speed"]["quads"].get(str(s))
        if q:
            print(f"    level {s:3d}: 0deg=({q[0][0] >> 4},{q[0][1] >> 4})"
                  f"  45deg=({q[32][0] >> 4},{q[32][1] >> 4})"
                  f"  90deg=({q[64][0] >> 4},{q[64][1] >> 4})   [after asr.l #4]")
    print(f"  shot       {len(t['shot']['templates'])} reachable spawn templates, "
          f"{len(t['rom']['windows'])} ROM windows "
          f"({sum(w['len'] for w in t['rom']['windows'])} bytes)")
    if "--verify" in sys.argv:
        print("  VERIFY OK")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / ".gitignore").write_text("*\n", encoding="utf8")
    p = OUT / "player.tables.json"
    p.write_text(json.dumps(t), encoding="utf8")
    print(f"  wrote {p}  ({p.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
