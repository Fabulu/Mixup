#!/usr/bin/env python3
"""Generate src/tunables.js by reading the constants out of the ROM itself.

Every entry names the file offset of the operand byte in the original code, so
the generated module is provably the game's own numbers rather than values
copied by hand out of a document.  Source: docs/00-MASTER-REFERENCE.md §10.

Usage:  python tools/gen_tunables.py [--check]
        --check verifies each byte still equals the expected value and exits
        non-zero on mismatch (guards against a bad offset silently drifting).
"""
