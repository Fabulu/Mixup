HEADER = '''// GENERATED by tools/gen_tunables.py -- do not edit by hand.
//
// Every value below was read out of the original ROM at the cited file offset,
// so this module is the game's own numbers, not a hand transcription.
// Re-generate with:  python tools/gen_tunables.py
//
// Units: positions and velocities are 12.4 fixed point (SUBPX = 16 per pixel).
// Velocity Y is POSITIVE UP (the game computes `Y -= VelY`).
//
// The mod system overrides these at load time; nothing else may inline them.

export const SUBPX = 16;

export const DEFAULT_TUNABLES = {
'''

FOOTER = '''};

/** Fresh mutable copy; mods mutate the copy, never DEFAULT_TUNABLES. */
export function makeTunables(overrides = {}) {
  return { ...DEFAULT_TUNABLES, ...overrides };
}
'''


def main():
    check = '--check' in sys.argv
    rom = Rom()
    lines = []
    problems = []

    for name, off, expect, signed, comment in TUNABLES:
        if off is None:
            lines.append('')
            lines.append(f'  // {name[3:]}')
            continue
        actual = rom.data[off]
        if actual != expect:
            problems.append(f'{name}: offset ${off:05X} is ${actual:02X}, '
                            f'expected ${expect:02X}')
        val = actual - 256 if (signed and actual > 127) else actual
        note = f'  // ${off:05X}'
        if comment:
            note += f' - {comment}'
        lines.append(f'  {name}: {val},{note}')

    if problems:
        print('MISMATCH between ROM and documented offsets:', file=sys.stderr)
        for p in problems:
            print('  ' + p, file=sys.stderr)
        return 1

    if check:
        print(f'ok - all {len([t for t in TUNABLES if t[1] is not None])} '
              f'tunables match the ROM')
        return 0

    out = os.path.join(GAME_ROOT, 'src', 'tunables.js')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', encoding='utf-8') as f:
        f.write(HEADER + '\n'.join(lines) + '\n' + FOOTER)
    print(f'wrote {out} ({len([t for t in TUNABLES if t[1] is not None])} constants)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
